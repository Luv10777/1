-- ============================================================
-- V20 · 回复末尾的过渡语
--
-- 回复打断讲解之后，直接从断点接着讲很突兀。回复现在可以带一句过渡语
-- （“好，咱们接着说。”），和回复合成在同一段音频里：
--
--   outro_text          : 过渡语原文；没有则为空
--   outro_offset_millis : 过渡语在音频里从哪一毫秒开始
--
-- 说不说由播报端在播到这个位置时决定：后面紧跟着另一条回复，或者没有讲解可以
-- 接回去，就在这里结束。
-- ============================================================

ALTER TABLE live_speech_items
    ADD COLUMN outro_text          VARCHAR(100),
    ADD COLUMN outro_offset_millis BIGINT;
